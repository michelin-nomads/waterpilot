"""Generate ``docs/data-readiness.md``: the coverage matrix derived from the runtime
readiness policy, so the document cannot drift from what the gate enforces (drift test:
``tests/test_coverage_matrix.py``).

Usage:  uv run python -m waterpilot.cli.coverage_matrix <output.md>
"""

from __future__ import annotations

import json
import sys
from collections.abc import Sequence
from pathlib import Path

from waterpilot.domain.readiness import (
    CAPABILITY_POLICY,
    INPUTS,
    METRICS,
    REVIEWED_MODELS,
    InputId,
    InputReadiness,
    ReadinessState,
    assess_metric,
)

MATRIX = Path(__file__).resolve().parents[5] / "docs" / "domain" / "capability-matrix.json"
DEMO_SOURCES = ("synthetic-utility-supply-demo",)


def _yes(flag: bool) -> str:
    return "yes" if flag else "no"


def _table(header: tuple[str, ...], rows: Sequence[tuple[str, ...]]) -> list[str]:
    widths = [max(len(h), *(len(r[i]) for r in rows)) for i, h in enumerate(header)]

    def line(cells: tuple[str, ...]) -> str:
        return "| " + " | ".join(c.ljust(w) for c, w in zip(cells, widths, strict=True)) + " |"

    return [line(header), "| " + " | ".join("-" * w for w in widths) + " |", *map(line, rows)]


def _typed_in_only() -> dict[str, ReadinessState]:
    """Best metric state if a person typed in every input that allows manual entry and
    nothing was imported, computed by the same ``assess_metric`` the API uses."""
    inputs: dict[InputId, InputReadiness] = {}
    for req in INPUTS.values():
        if req.manual_entry and req.owner_prompt is None:
            inputs[req.id] = InputReadiness(
                input=req.id,
                state=ReadinessState.USER_ENTERED,
                reasons=(),
                manual_input_id="typed-in",
                manual_value="1",
            )
        else:
            inputs[req.id] = InputReadiness(
                input=req.id, state=ReadinessState.UNAVAILABLE, reasons=()
            )
    return {m.metric: assess_metric(m, inputs).state for m in METRICS}


def render() -> str:
    matrix = json.loads(MATRIX.read_text(encoding="utf-8"))
    families = {c["capability"]: c["candidateSourceFamilies"] for c in matrix["capabilities"]}
    out = [
        "# WaterPilot — Coverage matrix and data readiness",
        "",
        "<!-- Generated by `npm run coverage-matrix` from `waterpilot.domain.readiness` and",
        "     `docs/domain/capability-matrix.json`. Do not edit by hand; a test checks drift. -->",
        "",
        "What WaterPilot can show for an area depends on imported, licence-reviewed and validated",
        "sources, plus values a person enters. This file lists what the runtime gate requires",
        "(`docs/domain/data-readiness-gate.md`, ADR 0008); `docs/data/ingestion-runbook.md`",
        "explains how a source is registered, reviewed and imported.",
        "",
        "## Status",
        "",
        "- **No real source is registered or imported.** For every real area, every capability",
        "  below is `unavailable` until a source passes licence review, ingestion and",
        "  validation. Live ingestion against GCP is **pending** (not verified).",
        "- Candidate source families come from `capability-matrix.json`. They are **not",
        "  registered**: each needs a licence review and confirmation of its coverage and",
        "  dates before use. Google Earth Engine is not assumed to be available.",
        f"- Demo-only sources (synthetic, never shown in pilot mode): {', '.join(DEMO_SOURCES)}.",
        "- Reviewed models: "
        + (", ".join(sorted(c.value for c in REVIEWED_MODELS)) or "none")
        + ". Capabilities that need one stay `partial` at best.",
        "- Reporting windows and freshness bounds are **PROPOSED** and need domain review.",
        "",
        "Readiness states, from best to worst: `available` (validated, licensed, in coverage and",
        "fresh), `user_entered` (typed in by the person, with a source note), `partial`",
        "(usable with a caveat), `stale` (too old) and `unavailable`. Missing data is never",
        "shown as zero.",
        "",
        "## Capabilities",
        "",
    ]
    cap_rows = [
        (
            cap.value,
            policy.technical_support.value,
            _yes(policy.requires_local_measurement),
            _yes(policy.requires_reviewed_model),
            "point-in-time" if policy.window_days is None else f"{policy.window_days} days",
            f"{policy.max_age_days} days",
            ", ".join(families.get(cap.value, [])) or "none",
            "none",
        )
        for cap, policy in CAPABILITY_POLICY.items()
    ]
    out += _table(
        (
            "Capability",
            "Technical support",
            "Local measurement",
            "Reviewed model",
            "Window",
            "Max age",
            "Candidate source families (not registered)",
            "Registered real sources",
        ),
        cap_rows,
    )
    out += ["", "## Inputs", ""]
    input_rows = [
        (
            req.id.value,
            req.label,
            req.unit.value,
            req.capability.value if req.capability else "none defined",
            _yes(req.manual_entry and req.owner_prompt is None),
            "none" if req.max_age_days is None else f"{req.max_age_days} days",
            req.owner_prompt or "-",
        )
        for req in INPUTS.values()
    ]
    out += _table(
        ("Input", "Label", "Unit", "Source capability", "Manual entry", "Max age", "Arrives with"),
        input_rows,
    )
    typed = _typed_in_only()
    out += ["", "## Metrics", ""]
    metric_rows = [
        (
            m.metric,
            ", ".join(i.value for i in m.required),
            ", ".join(i.value for i in m.optional) or "-",
            _yes(m.daily_series),
            typed[m.metric].value,
        )
        for m in METRICS
    ]
    out += _table(
        ("Metric", "Required inputs", "Optional inputs", "Daily series", "Typed-in values only"),
        metric_rows,
    )
    out += [
        "",
        "`Typed-in values only` is the best state a metric reaches when a person enters every",
        "input that allows it and nothing is imported. Metrics that need a daily series stay",
        "`unavailable` until a validated source supplies one.",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    Path(argv[0]).write_text(render(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
