"""Reports (immutable once finalized; archive is the only later transition) and
proposals (generated by a durable job, reviewed before any download)."""

from __future__ import annotations

from enum import StrEnum

from pydantic import Field

from waterpilot.domain.economics import OptionEconomics
from waterpilot.domain.impact_records import ReviewNeed
from waterpilot.domain.planning import Goal, ImpactAssessment, SiteProfile
from waterpilot.domain.records import Record
from waterpilot.domain.values import Frozen, UtcDateTime


class ReportStatus(StrEnum):
    FINALIZED = "finalized"
    ARCHIVED = "archived"


class Report(Record):
    owner_uid: str
    session_id: str
    community_id: str | None = None
    area_id: str
    title: str = Field(min_length=1, max_length=200)
    status: ReportStatus = ReportStatus.FINALIZED
    goal: Goal
    plan_option_id: str
    finalized_at: UtcDateTime
    archived_at: UtcDateTime | None = None
    plan_name: str | None = Field(default=None, max_length=200)
    site_profile: SiteProfile | None = None
    """The community type and occupied homes the person gave, copied at finalization;
    None for older reports or when none was given."""
    impact: ImpactAssessment | None = None
    """The chosen option's impact assessment, copied at finalization with its provenance
    (ADR 0013); None for reports finalized before it existed."""
    economics: OptionEconomics | None = None
    """The chosen option's economics, copied at finalization (ADR 0014) so costs, payback
    and the funding gap export exactly as compared; None for older reports."""

    def required_reviews(self) -> tuple[ReviewNeed, ...]:
        wider = self.impact.wider if self.impact else None
        return tuple(r for r in wider.reviews if r.required) if wider else ()

    def impact_status(self) -> str:
        """``assessed``, or why there is no wider-impact assessment (older records)."""
        if self.impact is None:
            return "not_recorded"
        return "assessed" if self.impact.wider is not None else "not_assessed"


class ProposalSection(StrEnum):
    EXECUTIVE_SUMMARY = "executive_summary"
    BASELINE = "baseline"
    PLAN = "plan"
    WIDER_IMPACT = "wider_impact"
    COSTS = "costs"
    FUNDING = "funding"
    ASSUMPTIONS = "assumptions"
    SOURCES = "sources"


class ProposalStatus(StrEnum):
    QUEUED = "queued"
    DRAFTING = "drafting"
    NEEDS_REVIEW = "needs_review"
    APPROVED = "approved"
    FAILED = "failed"


class ProposalApplicant(Frozen):
    """Applicant-supplied details captured with one immutable proposal revision."""

    name: str = Field(min_length=1, max_length=200)
    organization: str = Field(min_length=1, max_length=200)
    category: str = Field(min_length=1, max_length=100)
    contact_email: str | None = Field(default=None, max_length=254)
    assumptions: tuple[str, ...] = Field(default=(), max_length=30)


class Proposal(Record):
    owner_uid: str
    report_id: str
    scheme_id: str | None = None
    applicant: ProposalApplicant | None = None
    sections: tuple[ProposalSection, ...] = Field(min_length=1, max_length=len(ProposalSection))
    status: ProposalStatus = ProposalStatus.QUEUED
    job_id: str
    artifact_key: str | None = None
    html_artifact_key: str | None = None
    flagged_count: int = Field(default=0, ge=0)
