"""Reports (immutable once finalized; archive is the only later transition) and
proposals (generated by a durable job, reviewed before any download)."""

from __future__ import annotations

from enum import StrEnum

from pydantic import Field

from waterlens.domain.planning import Goal
from waterlens.domain.records import Record
from waterlens.domain.values import UtcDateTime


class ReportStatus(StrEnum):
    FINALIZED = "finalized"
    ARCHIVED = "archived"


class Report(Record):
    owner_uid: str
    session_id: str
    community_id: str | None = None
    area_id: str
    title: str = Field(min_length=1, max_length=200)
    status: ReportStatus = ReportStatus.FINALIZED
    goal: Goal
    plan_option_id: str
    finalized_at: UtcDateTime
    archived_at: UtcDateTime | None = None


class ProposalSection(StrEnum):
    EXECUTIVE_SUMMARY = "executive_summary"
    BASELINE = "baseline"
    PLAN = "plan"
    COSTS = "costs"
    FUNDING = "funding"
    ASSUMPTIONS = "assumptions"
    SOURCES = "sources"


class ProposalStatus(StrEnum):
    QUEUED = "queued"
    DRAFTING = "drafting"
    NEEDS_REVIEW = "needs_review"
    APPROVED = "approved"
    FAILED = "failed"


class Proposal(Record):
    owner_uid: str
    report_id: str
    sections: tuple[ProposalSection, ...] = Field(min_length=1, max_length=len(ProposalSection))
    status: ProposalStatus = ProposalStatus.QUEUED
    job_id: str
    artifact_key: str | None = None
    flagged_count: int = Field(default=0, ge=0)
